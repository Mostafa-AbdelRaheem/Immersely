USERNAME_MIN = 3
USERNAME_MAX = 20


def derive_username(email: str, taken: set[str]) -> str:
    """Username from the email's local part, unique against `taken`.

    Lowercase; anything outside [a-z0-9_] becomes "_"; padded to the minimum
    length; truncated to the maximum; numeric suffix (2, 3, ...) on collision.
    """
    local = email.split("@", 1)[0].lower()
    base = re.sub(r"[^a-z0-9_]", "_", local)
    if len(base) < USERNAME_MIN:
        base += "_user"
    base = base[:USERNAME_MAX]

    candidate = base
    n = 1
    while candidate in taken:
        n += 1
        suffix = str(n)
        candidate = base[: USERNAME_MAX - len(suffix)] + suffix
    return candidate


